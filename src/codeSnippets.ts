export function mapActiveLines(algorithmId: AlgorithmId, language: CodeLanguage, cppLines: number[]) {
  const snippet = codeSnippets[algorithmId][language];
  const mapped = cppLines.flatMap((line) => {
    const target = snippet.lineMap[line] ?? line;
    return Array.isArray(target) ? target : [target];
  });

  return [...new Set(mapped)];
}
